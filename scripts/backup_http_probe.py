"""Streaming HTTP upload probe for the isolated P6 synthetic dataset."""

import json
from pathlib import Path

from app.backup import archive, control, workflow
from app.services import backups
from backup_capacity import guard, measure, upload_http


def main():
    guard()
    root = Path("/data/control/http-probe")
    root.mkdir(exist_ok=True)
    path, _ = measure("HTTP probe export", lambda: archive.export_archive(root))
    view = measure("HTTP multipart upload", lambda: upload_http(path))
    measure(
        "HTTP upload isolated validation",
        lambda: workflow.process(control.require(view.restore_id)),
    )
    result = backups.restore_view(view.restore_id)
    assert result.status == "ready", result.message
    print(
        json.dumps(
            {
                "restore_id": str(result.restore_id),
                "archive_bytes": path.stat().st_size,
                "status": result.status,
                "summary": result.summary,
            }
        ),
        flush=True,
    )
    # Retain the receipt, reclaim only this probe's generated byte copies.
    import shutil

    shutil.rmtree(root)
    directory = control.directory(view.restore_id)
    for child in directory.iterdir():
        if child.name == "state.json":
            continue
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()


if __name__ == "__main__":
    main()
